def main():
    raw = subprocess.run(["gh", "issue", "list", "--repo", REPO, "--state", "all",
                          "--limit", "500", "--json", "title"],
                         capture_output=True, text=True, check=True).stdout
    have = {x["title"] for x in json.loads(raw)}
    created = skipped = failed = 0
    for n, title, target, typ, goal, acc in I:
        full = f"L5-{n-140:03d} — {title}"
        if full in have:
            skipped += 1
            continue
        body = (f"## Goal\n{goal}\n\n"
                f"## Context\nFrom `opengate-biz.webm`: a company wants to work with us; model it as a "
                f"tenant in OpenGate with 1ID login, either a group of companies or a single legal "
                f"entity, each company with its own org chart, departments and folders.\n\n"
                f"**Work happens in:** `{'abn.platform.opengate' if target == 'opengate' else ('abn.os.enterprise' if target == 'enterprise' else 'both repos (contract here, implementation in abn.platform.opengate)')}`\n\n"
                "## Acceptance criteria\n" + "\n".join(f"- [ ] {a}" for a in acc))
        r = subprocess.run(["gh", "issue", "create", "--repo", REPO, "--title", full,
                            "--label", f"loop:5,{typ},target:{target}", "--body", body],
                           capture_output=True, text=True)
        if r.returncode == 0:
            created += 1
            print("created:", full)
        else:
            failed += 1
            print("FAILED:", full, r.stderr[:160])
    print(f"done: created={created} skipped={skipped} failed={failed} total={len(I)}")


if __name__ == "__main__":
    main()
