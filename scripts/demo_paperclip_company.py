#!/usr/bin/env python3
"""Record the compiler demo end to end (issue #261).

Runs the whole ladder against a throwaway copy of the fixture model and writes
`docs/core/paperclip-demo.md` with the commands and their real output. The
transcript is committed, and `--check` proves it still reproduces: CI runs the
demo again and fails on any difference.

    python scripts/demo_paperclip_company.py            # write the transcript
    python scripts/demo_paperclip_company.py --check    # does it reproduce?

Paths under the temporary directory are normalised to `$DEMO`, so the transcript
does not depend on where it ran.
"""
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLI = ROOT / "bin" / "paperclip-company"
MODEL = ROOT / "tests" / "fixtures" / "paperclip-model"
OUT = ROOT / "docs" / "core" / "paperclip-demo.md"
PY = sys.executable

STEPS = [
    ("compile every company that opted in (the CI gate)", ["--all", "--check"]),
    ("see the crew", ["--show", "--company", "demo"]),
    ("render the sheet a reviewer reads", ["--render", "--company", "demo",
                                            "--out", "$DEMO/crew.md"]),
    ("write templates and leave a record", ["--all", "--out-dir", "$DEMO/out",
                                            "--record"]),
    ("measure it", ["--metrics"]),
    ("prove the alert can fire", ["--drill"]),
]


def transcript():
    with tempfile.TemporaryDirectory() as tmp:
        demo = Path(tmp) / "demo"
        shutil.copytree(MODEL, demo)
        lines = [
            "<!-- generated by scripts/demo_paperclip_company.py; do not edit — "
            "run the script and commit the new transcript -->",
            "# The compiler, end to end",
            "",
            "One run against a throwaway copy of `tests/fixtures/paperclip-model`",
            "(the fixture companies `demo` and `nested`). Reproduce it with:",
            "",
            "```",
            "python scripts/demo_paperclip_company.py",
            "```",
            "",
        ]
        for label, args in STEPS:
            real = [str(demo) if a == "$DEMO" else a.replace("$DEMO", str(demo))
                    for a in args]
            shown = " ".join(["--root tests/fixtures/paperclip-model", *args])
            command = [PY, str(CLI), "--root", str(demo), *real]
            result = subprocess.run(command, capture_output=True, text=True)
            output = ((result.stdout or "") + (result.stderr or "")).strip()
            output = output.replace(str(demo), "$DEMO")
            lines += [f"## {label}", "", "```", f"$ bin/paperclip-company {shown}",
                      output or "(no output)", "```", ""]
            if result.returncode != 0 and label != "prove the alert can fire":
                lines += [f"(exit {result.returncode})", ""]
        lines += [
            "## What the run shows",
            "",
            "The gate compiles only the companies that declared `paperclip:",
            "compile: true`; `--show` and `--record` are the human and the",
            "evidence views; `--metrics` is the same state as numbers; and the",
            "drill proves the critical alert fires. Nothing here needs Paperclip",
            "running — that is the adapter's job (PC1-03, #262), not the",
            "compiler's.",
            "",
        ]
        return "\n".join(lines)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    text = transcript()
    if "--check" in argv:
        current = OUT.read_text() if OUT.is_file() else ""
        if current != text:
            print("demo --check RED: docs/core/paperclip-demo.md does not reproduce",
                  file=sys.stderr)
            import difflib
            diff = list(difflib.unified_diff(current.splitlines(),
                                             text.splitlines(),
                                             "committed", "fresh", lineterm=""))
            print("\n".join(diff[:40]), file=sys.stderr)
            return 1
        print("demo --check: the transcript reproduces — OK")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"demo: wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
