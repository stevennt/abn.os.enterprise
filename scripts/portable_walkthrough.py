#!/usr/bin/env python3
"""Record the portability runbook end to end (issue #328).

Copies the tiny fixture company into a temp checkout and walks the surface:
export, record, the silent re-record, the history, show, verify, diff, import into
a clean checkout, the two refusals an operator actually meets, the forced
rollback, and `check`. Writes `docs/core/portability-walkthrough.md` with each
command and its output.

    python scripts/portable_walkthrough.py            # write the transcript
    python scripts/portable_walkthrough.py --check    # does it reproduce?

The temp path prints as `$TMP`; log timestamps are normalised. The `bundle-…` id
is **not** normalised: it is content, so it is stable and worth reading.
"""

import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BIN = ROOT / "bin" / "portable"
TINY = ROOT / "tests" / "fixtures" / "portability" / "tiny"
OUT = ROOT / "docs" / "core" / "portability-walkthrough.md"
PLATFORM = "contract-2026.11.3"


def stable(text, tmp):
    text = text.replace(str(tmp), "$TMP")
    text = re.sub(r'"(at|createdAt)": "[^"]+"', r'"\1": "<time>"', text)
    text = re.sub(r"^(\s*)\d{4}-\d{2}-\d{2}T\S+", r"\1<time>", text,
                  flags=re.M)
    return "\n".join(line for line in text.splitlines()
                     if not line.startswith("warning:")).strip("\n")


def call(*argv, expect=0):
    result = subprocess.run([sys.executable, str(BIN), *map(str, argv)],
                            capture_output=True, text=True)
    output = ((result.stdout or "") + (result.stderr or "")).strip()
    if result.returncode != expect:
        raise SystemExit(f"walkthrough: portable {argv} exited "
                         f"{result.returncode}, expected {expect}\n{output}")
    return output


def transcript():
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(tmp)
        root = base / "source"
        shutil.copytree(TINY, root)
        lines = [
            "<!-- generated by scripts/portable_walkthrough.py; do not edit — run "
            "the script and commit the new transcript -->",
            "# Company portability, end to end",
            "",
            "One company (`acme`, the tiny fixture) moved between two checkouts:",
            "exported, recorded under its own id, verified, imported into a clean",
            "tree, and rolled back — with the two refusals an operator actually",
            "meets on the way. The temp path prints as `$TMP`; log timestamps are",
            "normalised, the `bundle-…` id is real because it is content.",
            "Reproduce the whole transcript with:",
            "",
            "```",
            "python scripts/portable_walkthrough.py",
            "```",
            "",
        ]
        steps = []

        def add(label, command, output, note, exit_code=None):
            if exit_code is not None:
                output += f"\n(exit {exit_code})"
            steps.append((label, command, output, note))

        output = call("export", "--company", "acme", "--root", root,
                      "--platform", PLATFORM)
        add("Export the company",
            "bin/portable export --company acme --root $TMP/source "
            "--platform contract-2026.11.3",
            output,
            "The line carries the three things an operator needs: the id, how many"
            " artefacts travel, and the pin it was compiled against beside the"
            " platform it is going to.")

        output = call("record", "--company", "acme", "--root", root,
                      "--platform", PLATFORM)
        bundle_id = output.split()[1]
        add("Record it",
            "bin/portable record --company acme --root $TMP/source "
            "--platform contract-2026.11.3",
            output,
            "The carrier is stored under its own id: "
            f"`companies/acme/bundles/{bundle_id}/`, with the template beside the"
            " manifest.")

        output = call("record", "--company", "acme", "--root", root,
                      "--platform", PLATFORM)
        add("Recording again is silent",
            "bin/portable record …",
            output,
            "The id is the identity, so nothing moved and nothing is written — the"
            " metadata in the manifest (`createdAt`, the platform) does not make a"
            " second bundle.")

        output = call("bundles", "--company", "acme", "--root", root)
        add("The history",
            "bin/portable bundles --company acme --root $TMP/source",
            output,
            "Newest first, with the action that produced each row.")

        output = call("show", "--company", "acme", "--bundle", bundle_id,
                      "--root", root)
        add("See one carrier",
            f"bin/portable show --company acme --bundle {bundle_id} "
            "--root $TMP/source",
            output,
            "Every artefact by kind, its version, and the first twelve characters"
            " of its digest. The company's own files are `org`; the industry's are"
            " flows, rules or its pack.")

        output = call("verify", "--bundle",
                      root / "companies" / "acme" / "bundles" / bundle_id
                      / "bundle.json", "--root", root)
        add("Verify it against the checkout",
            f"bin/portable verify --bundle "
            f"$TMP/source/companies/acme/bundles/{bundle_id}/bundle.json "
            "--root $TMP/source",
            output,
            "Two questions are asked by two things: the carrier's own integrity"
            " always, and every artefact's digest where the checkout has the"
            " company. This is the second.")

        output = call("diff", "--left",
                      root / "companies" / "acme" / "bundles" / bundle_id
                      / "bundle.json",
                      "--right",
                      root / "companies" / "acme" / "bundles" / bundle_id
                      / "bundle.json")
        add("Diff two bundles",
            "bin/portable diff --left …/bundle.json --right …/bundle.json",
            output,
            "Manifest to manifest, per `kind:id`. Two exports of one state differ"
            " in nothing, which is what a rollback target must be.")

        clean = base / "import"
        shutil.copytree(TINY, clean)
        (clean / "companies" / "acme" / "paperclip-company.json").unlink()
        carrier = base / "handover"
        carrier.mkdir()
        shutil.copyfile(root / "companies" / "acme" / "bundles" / bundle_id
                        / "bundle.json", carrier / "bundle.json")
        shutil.copyfile(root / "companies" / "acme" / "bundles" / bundle_id
                        / "paperclip-company.json", carrier / "paperclip-company.json")
        output = call("import", "--bundle", carrier / "bundle.json", "--root",
                      clean, "--platform", PLATFORM)
        add("Import into a clean checkout",
            "bin/portable import --bundle $TMP/handover/bundle.json "
            "--root $TMP/import --platform contract-2026.11.3",
            output,
            "The target has the model but not the compiled template; the artefacts"
            " travel with the bundle, so their absence there is not a fault.")

        output = call("record", "--company", "acme", "--root", clean,
                      "--platform", PLATFORM)
        add("The same id on the other side",
            "bin/portable record --company acme --root $TMP/import "
            "--platform contract-2026.11.3",
            output,
            f"`{bundle_id}` again: the two checkouts agree the company is the"
            " same, because the id is content and nothing about the move changed"
            " the content.")

        output = call("export", "--company", "acme", "--root", root,
                      "--platform", "contract-2026.09.0", expect=1)
        add("A bundle newer than the platform is refused",
            "bin/portable export --company acme --root $TMP/source "
            "--platform contract-2026.09.0",
            output,
            "`E-PORT-06`: the importer must not silently drop what it cannot read."
            " The opposite direction — an older bundle into a newer platform — is"
            " allowed and recorded.", exit_code=1)

        path = clean / "customers" / "acme"
        path.mkdir(parents=True)
        (path / "org.json").write_text("{}\n")
        doc = json.loads((clean / "companies" / "acme"
                          / "paperclip-company.json").read_text())
        doc["source"]["files"] = list(doc["source"]["files"]) + \
            ["customers/acme/org.json"]
        (clean / "companies" / "acme" / "paperclip-company.json").write_text(
            json.dumps(doc, indent=2) + "\n")
        output = call("export", "--company", "acme", "--root", clean,
                      "--platform", PLATFORM, expect=1)
        add("A bundle that carries tenant data is refused",
            "bin/portable export --company acme --root $TMP/import "
            "--platform contract-2026.11.3",
            output,
            "`E-PORT-05`: a company bundle is the org, never a tenant's documents."
            " A business leaving with another business's papers is not"
            " portability.", exit_code=1)

        edited = clean / "companies" / "acme" / "paperclip-company.json"
        restored = json.loads((TINY / "companies" / "acme"
                               / "paperclip-company.json").read_text())
        edited.write_text(json.dumps(restored, indent=2) + "\n")
        doc = json.loads(edited.read_text())
        doc["label"] = "ACME (edited after the bundle)"
        edited.write_text(json.dumps(doc, indent=2) + "\n")

        output = call("rollback", "--company", "acme", "--to", bundle_id,
                      "--root", clean, expect=1)
        add("A rollback that would overwrite is refused",
            f"bin/portable rollback --company acme --to {bundle_id} "
            "--root $TMP/import",
            output,
            "`E-PORT-04`: a rollback replaces a live compiled model, so it is"
            " deliberate. The refusal is the feature.", exit_code=1)

        output = call("rollback", "--company", "acme", "--to", bundle_id,
                      "--root", clean, "--force")
        add("And --force does it, on the record",
            f"bin/portable rollback --company acme --to {bundle_id} "
            "--root $TMP/import --force",
            output,
            "The log gets a `rollback` row naming what it restored, and the"
            " checkout re-exports to the same id it went back to — which makes the"
            " id a proof of the restore, not a label.")

        output = call("check", "--root", clean)
        add("Check the store",
            "bin/portable check --root $TMP/import",
            output,
            "Every stored carrier against its own manifest, every directory named"
            " by its bundle id, every log row naming a carrier that exists.")

        for label, command, output, *note in steps:
            lines.extend([f"## {label}", ""])
            if note:
                lines.extend([" ".join(note), ""])
            lines.extend(["```", f"$ {command}",
                          *stable(output, base).splitlines(), "```", ""])

        lines.extend([
            "## What the run shows",
            "",
            "* A bundle is the template plus everything it names, and its id is",
            "  the digest of exactly that — so two exports of one state are one",
            "  bundle, and a re-record writes nothing.",
            "* Three refusals protect the *scope*: tenant data, a newer contract,",
            "  and an absolute path. None of them is a warning.",
            "* A rollback is an import of a stored id, made deliberate: it needs",
            "  `--force` to overwrite, and it leaves a row saying it happened.",
            "* The company's own files are `org`; an industry's are flows, rules",
            "  or its pack. A repo-shipped artefact is versioned by the pin it",
            "  ships with unless the file declares its own.",
            "",
            "The contract: [portability.md](portability.md).",
            "",
        ])
        return "\n".join(lines)


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    text = transcript()
    if "--check" in argv:
        current = OUT.read_text() if OUT.is_file() else ""
        if current != text:
            print("portability walkthrough --check RED: "
                  "docs/core/portability-walkthrough.md does not reproduce",
                  file=sys.stderr)
            import difflib
            diff = list(difflib.unified_diff(current.splitlines(),
                                             text.splitlines(),
                                             "committed", "fresh", lineterm=""))
            print("\n".join(diff[:40]), file=sys.stderr)
            return 1
        print("portability walkthrough --check: the transcript reproduces — OK")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"portability walkthrough: wrote {OUT.relative_to(ROOT)} "
          f"({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
